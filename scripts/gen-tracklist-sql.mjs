// Generates SQL INSERT statements for the tracklists table from raw 1001tracklists data.
// Usage: node scripts/gen-tracklist-sql.mjs

function parseTime(t) {
  const parts = t.replace(/^0:/, '').split(':').map(Number);
  if (t.match(/^\d+:\d+:\d+$/)) {
    const [h, m, s] = t.split(':').map(Number);
    return h * 3600000 + m * 60000 + s * 1000;
  }
  if (parts.length === 2) return parts[0] * 60000 + parts[1] * 1000;
  if (parts.length === 1) return parts[0] * 1000;
  return 0;
}

function cleanTracks(raw) {
  const seen = new Set();
  const tracks = [];
  let num = 0;
  for (const t of raw) {
    if (t.num === 0) continue;
    const key = t.time;
    if (seen.has(key)) continue;
    seen.add(key);
    num++;
    const timeMs = parseTime(t.time);
    tracks.push({
      num,
      time: t.time,
      timeMs,
      artist: t.artist,
      title: t.title,
    });
  }
  return tracks;
}

function sqlInsert(artistName, stage, tracks, sourceUrl, setDate) {
  const json = JSON.stringify(tracks).replace(/'/g, "''");
  return `INSERT INTO tracklists (artist_name, festival_id, stage, set_date, tracks, source, source_url)
VALUES ('${artistName.replace(/'/g, "''")}', 'edc-lv-2026', '${stage}', '${setDate}', '${json}'::jsonb, '1001tracklists', '${sourceUrl}')
ON CONFLICT (artist_name, festival_id) DO UPDATE SET tracks = EXCLUDED.tracks, source = EXCLUDED.source, source_url = EXCLUDED.source_url, stage = EXCLUDED.stage, set_date = EXCLUDED.set_date;`;
}

