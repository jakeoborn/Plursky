#!/usr/bin/env node
// build-memory-index.mjs: Plursky's MEMORY.md, generated, never hand-edited.
//
// Same idea as Dim Hour's scripts/build-memory-index.cjs. The hand-kept index
// had drifted the way hand-kept indexes do: on 2026-11-07, 11 memory files had
// no line at all and one file had two. Generating the index makes both
// impossible. Every memory file gets exactly one line, and only files that
// exist get one.
//
// It also writes a short STATE block, read from the sources of truth, so a
// compact never drops where the queue stands:
//   main + versions   git origin/main (sw.js APP_VER, pbxproj on main)
//   open / merged PRs gh pr list
//   queue rows        TODO.md open rows + the newest AGENT_LOG.md entry, on origin/main
//   findings          the inbox plugin's open f-numbers for this repo
//   handoff           newest ~/Plursky-private/instinct/HANDOFF-*.md, run through check-handoff
// Each state line is a one-line pointer; nothing is copied from a source in bulk.
//
//   node scripts/memory/build-memory-index.mjs                       # regenerate
//   node scripts/memory/build-memory-index.mjs --check               # 0 fresh · 1 stale · 2 cannot verify
//   node scripts/memory/build-memory-index.mjs --self-test           # fixtures only, no network (CI)
//   node scripts/memory/build-memory-index.mjs --migrate-from-index  # one-time: hand index → frontmatter
//
// A memory reaches the auto-loaded MEMORY.md only with `metadata.pin: true` in
// its OWN frontmatter. Everything else is listed in MEMORY-ARCHIVE.md.
// Its line is `metadata.title` + `metadata.hook` (falling back to name and
// description), so the line is edited in the memory file, never in the index.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { findSecrets, redact, validateHandoff } from "./check-handoff.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "../..");

// The loader stops reading MEMORY.md around here and drops the tail silently,
// so this is a fail-closed build error, not a warning (Dim Hour measured it).
export const LOAD_CAP = 24_400;
// Covers the longest hand-written hook on 2026-11-07 (migration keeps every
// clause). LOAD_CAP, not this, is what bounds the file.
export const HOOK_CAP = 400;
const STATE_ITEM_CAP = 12;

export const HEADER = `> ⚙️ **GENERATED by \`node scripts/memory/build-memory-index.mjs\` (Plursky repo). Do not hand-edit:** \`--check\` fails on any drift.
> A line changes in its memory file's \`metadata.title\`/\`metadata.hook\`; only \`metadata.pin: true\` files load here. The rest: [MEMORY-ARCHIVE.md](MEMORY-ARCHIVE.md).
> Handoff notes: \`node scripts/memory/check-handoff.mjs --template\`; check one with \`… <file> --live\`.`;
const COLD_HEADER = `> 📁 Un-pinned memories. Not auto-loaded; read on demand.
> ⚙️ GENERATED by \`node scripts/memory/build-memory-index.mjs\`. Do not hand-edit. Hot half: [MEMORY.md](MEMORY.md).`;

// ── paths ────────────────────────────────────────────────────────────────
function git(args, cwd = REPO) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 60000 }).trim();
}
// The MAIN checkout, even from a worktree: Claude Code keys memory by the
// directory the session starts in (~/Plursky), not by ~/Plursky-<worktree>.
// Hard-coding this is how Dim Hour's old guard audited the wrong directory.
export function mainCheckout() {
  const common = git(["rev-parse", "--path-format=absolute", "--git-common-dir"]);
  return path.dirname(common);
}
export function defaultMemDir() {
  if (process.env.PLURSKY_MEMORY_DIR) return process.env.PLURSKY_MEMORY_DIR;
  const slug = mainCheckout().replace(/[/.]/g, "-");
  return path.join(os.homedir(), ".claude/projects", slug, "memory");
}

// ── frontmatter ──────────────────────────────────────────────────────────
function unquote(v) {
  v = v.trim();
  if (v.startsWith('"')) { try { return JSON.parse(v); } catch { /* fall through */ } }
  return v.replace(/^'(.*)'$/, "$1");
}
export function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const out = {};
  let inMeta = false;
  for (const raw of m[1].split(/\r?\n/)) {
    const indented = /^\s+\S/.test(raw);
    const kv = raw.trim().match(/^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$/);
    if (!kv) continue;
    if (kv[1] === "metadata" && !kv[2]) { inMeta = true; continue; }
    if (!indented) inMeta = false;
    (inMeta ? (out.metadata ||= {}) : out)[kv[1]] = unquote(kv[2]);
  }
  return out;
}
// Set metadata keys, JSON-quoted (a valid YAML double-quoted scalar, so
// backticks, colons and ** survive). Existing keys are replaced in place.
export function setMetadata(text, kv) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) throw new Error("no frontmatter");
  let lines = m[1].split("\n");
  let at = lines.findIndex(l => /^metadata:\s*$/.test(l));
  if (at < 0) { lines.push("metadata:"); at = lines.length - 1; }
  for (const [k, v] of Object.entries(kv)) {
    const val = typeof v === "string" ? JSON.stringify(v) : String(v);
    let end = at + 1;
    while (end < lines.length && /^\s+\S/.test(lines[end])) end++;
    const i = lines.slice(at + 1, end).findIndex(l => new RegExp(`^\\s+${k}:`).test(l));
    if (i >= 0) lines[at + 1 + i] = `  ${k}: ${val}`;
    else lines.splice(end, 0, `  ${k}: ${val}`);
  }
  return text.replace(m[0], `---\n${lines.join("\n")}\n---`);
}

// ── memories ─────────────────────────────────────────────────────────────
function capHook(s) {
  s = String(s || "").replace(/\s+/g, " ").trim();
  if (s.length <= HOOK_CAP) return s;
  const cut = s.slice(0, HOOK_CAP), sp = cut.lastIndexOf(" ");
  return (sp > HOOK_CAP * 0.6 ? cut.slice(0, sp) : cut).replace(/[,;:.\-—\s]+$/, "") + "…";
}
function titleOf(fm, file) {
  return fm.metadata?.title || String(fm.name || file.replace(/\.md$/, ""))
    .replace(/^(project|feedback|reference|user)[_-]/, "").replace(/[_-]/g, " ").replace(/^\w/, c => c.toUpperCase());
}
export function collectMemories(memDir) {
  return fs.readdirSync(memDir)
    .filter(f => f.endsWith(".md") && f !== "MEMORY.md" && f !== "MEMORY-ARCHIVE.md")
    .sort()
    .map(file => {
      const text = fs.readFileSync(path.join(memDir, file), "utf8");
      const fm = parseFrontmatter(text);
      const meta = fm.metadata || {};
      return {
        file,
        title: titleOf(fm, file),
        hook: capHook(meta.hook || fm.description || ""),
        // Frontmatter values are strings; compare as one, or every pin vanishes.
        pin: String(meta.pin ?? "").toLowerCase() === "true",
        order: Number(meta.pin_order ?? 9999),
      };
    });
}

// ── state from sources ───────────────────────────────────────────────────
// Each source returns { line } or { unavailable: reason }. An unavailable
// source is printed as such and makes --check exit 2: "could not read it" is
// never reported as "nothing there".
const short = s => String(s || "").slice(0, 8);
const clip = (s, n) => { s = String(s).replace(/\s+/g, " ").trim(); return s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s; };
function listCap(items, fmt) {
  const head = items.slice(0, STATE_ITEM_CAP).map(fmt).join(" · ");
  return items.length > STATE_ITEM_CAP ? `${head} · +${items.length - STATE_ITEM_CAP} more` : head;
}
// Error text comes from gh, git and the filesystem, so it is redacted before
// it can reach MEMORY.md (a gh error can quote a URL or header verbatim).
function guard(name, fn) {
  try { return { name, ...fn() }; } catch (e) { return { name, unavailable: clip(redact(String(e.message || e).split("\n")[0]), 120) }; }
}
function gh(args) {
  return JSON.parse(execFileSync("gh", args, { cwd: REPO, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 60000 }));
}

export function liveSources({ handoffDir, inboxStore, inboxKey }) {
  return () => {
    const out = [];
    let fetched = true;
    try { git(["fetch", "-q", "origin", "main"]); } catch { fetched = false; }
    out.push(guard("main", () => {
      if (!fetched) throw new Error("git fetch origin main failed; origin/main may be stale");
      const sha = git(["rev-parse", "origin/main"]);
      const ver = (git(["show", "origin/main:sw.js"]).match(/APP_VER\s*=\s*'(v\d+)'/) || [])[1];
      const pbx = git(["show", "origin/main:ios/App/App.xcodeproj/project.pbxproj"]);
      const mv = (pbx.match(/MARKETING_VERSION = ([\d.]+);/) || [])[1];
      const bn = (pbx.match(/CURRENT_PROJECT_VERSION = (\d+);/) || [])[1];
      if (!ver || !mv) throw new Error("version not found on origin/main");
      return { line: `main \`${short(sha)}\` · web ${ver} (sw.js) · native ${mv} (${bn}) per pbxproj on main` };
    }));
    out.push(guard("open PRs", () => {
      const prs = gh(["pr", "list", "--state", "open", "--limit", "100", "--json", "number,headRefOid,isDraft,baseRefName"])
        .sort((a, b) => b.number - a.number);
      if (!prs.length) return { line: "Open PRs: none" };
      return { line: `Open PRs (${prs.length}): ` + listCap(prs, p =>
        `#${p.number} ${short(p.headRefOid)} ${p.isDraft ? "draft" : "ready"}${p.baseRefName === "main" ? "" : `→${p.baseRefName}`}`) };
    }));
    out.push(guard("merged PRs", () => {
      // By merge time, not PR number: #390 merged after #397.
      const prs = gh(["pr", "list", "--state", "merged", "--limit", "20", "--json", "number,mergeCommit,mergedAt"])
        .sort((a, b) => String(b.mergedAt).localeCompare(String(a.mergedAt)) || b.number - a.number).slice(0, 5);
      return { line: "Last merged: " + (prs.map(p => `#${p.number} ${short(p.mergeCommit?.oid)}`).join(" · ") || "none") };
    }));
    out.push(guard("queue rows", () => {
      const todo = git(["show", "origin/main:TODO.md"]);
      const open = (todo.match(/^\s*- \[ \]/gm) || []).length;
      const log = git(["show", "origin/main:AGENT_LOG.md"]);
      const last = (log.match(/^- (20\d\d-\d\d-\d\d \d\d:\d\d CT) \| Author: ([^|]+)\| Lane: ([^|]+)\|/m) || []);
      return { line: `TODO.md: ${open} open rows · AGENT_LOG.md newest: ${last[1] ? `${last[1]}, ${last[2].trim()}, ${last[3].trim()}` : "no entry parsed"} (origin/main)` };
    }));
    out.push(guard("findings", () => {
      const store = inboxStore();
      if (!store) throw new Error("inbox plugin store not found");
      const ledger = JSON.parse(fs.readFileSync(store, "utf8"))[inboxKey]?.ledger;
      if (!ledger || !Array.isArray(ledger.findings)) throw new Error(`no findings ledger for ${inboxKey}`);
      const f = ledger.findings.filter(x => x && x.id);
      if (!f.length) return { line: "Findings open: none" };
      return { line: `Findings open (${f.length}): ` + listCap(f, x => `${x.id} ${clip(x.title, 48)}`) };
    }));
    out.push(guard("handoff", () => {
      if (!fs.existsSync(handoffDir)) throw new Error(`${handoffDir} not found`);
      const files = fs.readdirSync(handoffDir).filter(f => /^HANDOFF-.*\.md$/.test(f))
        .map(f => ({ f, t: fs.statSync(path.join(handoffDir, f)).mtimeMs })).sort((a, b) => b.t - a.t || (a.f < b.f ? 1 : -1));
      if (!files.length) return { line: "Handoff: none written" };
      const p = path.join(handoffDir, files[0].f);
      const res = validateHandoff(fs.readFileSync(p, "utf8"));
      const shown = p.replace(os.homedir(), "~");
      return { line: `Handoff: \`${shown}\` · format ${res.ok ? "PASS" : `FAIL (${clip(res.errors[0], 70)}; ${res.errors.length} issue(s))`}` };
    }));
    return out;
  };
}

// ── render ───────────────────────────────────────────────────────────────
const lineOf = m => `- [${m.title}](${m.file}) — ${m.hook}`;
export function render(memories, state) {
  const pinned = memories.filter(m => m.pin).sort((a, b) => a.order - b.order || (a.file < b.file ? -1 : 1));
  const cold = memories.filter(m => !m.pin);
  const stateLines = state.map(s => s.unavailable ? `- ⚠ ${s.name} UNAVAILABLE: ${s.unavailable}` : `- ${s.line}`);
  const hot = [
    HEADER, "",
    "## State (read from source at build time)", ...stateLines, "",
    `## Pinned memories (${pinned.length})`, ...pinned.map(lineOf), "",
    `> ${cold.length} more un-pinned in [MEMORY-ARCHIVE.md](MEMORY-ARCHIVE.md).`, "",
  ].join("\n");
  const archive = [COLD_HEADER, "", `## Un-pinned memories (${cold.length})`, ...cold.map(lineOf), ""].join("\n");
  return { hot, archive, pinned: pinned.length, cold: cold.length };
}

export function build({ memDir, sources }) {
  const memories = collectMemories(memDir);
  for (const m of memories) {
    const hits = findSecrets(`${m.title} ${m.hook}`);
    if (hits.length) throw new Error(`${m.file}: its index line would carry a credential value (${hits.join(", ")}). Fix the memory file.`);
  }
  const state = sources();
  // Both a line and an UNAVAILABLE reason are written to MEMORY.md; redact
  // the reason, and refuse a line (a source's data must never carry one).
  for (const s of state) {
    if (s.unavailable) s.unavailable = redact(s.unavailable);
    if (s.line && findSecrets(s.line).length) throw new Error(`state line "${s.name}" carries a credential value`);
  }
  const out = render(memories, state);
  const bytes = Buffer.byteLength(out.hot);
  if (bytes > LOAD_CAP) {
    throw new Error(`MEMORY.md would be ${bytes} B, over the ${LOAD_CAP} B load cap (the tail is silently dropped). Un-pin a memory or shorten a hook.`);
  }
  return { ...out, bytes, unavailable: state.filter(s => s.unavailable) };
}

// ── one-time migration from the hand-written index ───────────────────────
// Each linked file gets pin + title + hook from its own line, verbatim, so the
// generated line equals the hand one. A file linked twice gets both hooks
// joined, so nothing a line said is lost.
export function migrate(memDir) {
  const idx = fs.readFileSync(path.join(memDir, "MEMORY.md"), "utf8");
  const byFile = new Map();
  let order = 0;
  for (const l of idx.split("\n")) {
    const m = l.match(/^- \[(.+?)\]\(([^)]+\.md)\) — (.*)$/);
    if (!m) continue;
    const [, title, file, hook] = m;
    if (!fs.existsSync(path.join(memDir, file))) continue;
    const e = byFile.get(file);
    if (e) { e.title = `${e.title} · ${title}`; e.hook = `${e.hook} · ${title}: ${hook}`; }
    else byFile.set(file, { title, hook, order: order++ });
  }
  for (const [file, e] of byFile) {
    const p = path.join(memDir, file);
    fs.writeFileSync(p, setMetadata(fs.readFileSync(p, "utf8"), { pin: true, pin_order: e.order, title: e.title, hook: e.hook }));
  }
  return byFile;
}

// ── self-test (fixtures, no network, no home dir) ────────────────────────
function selfTest() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "plur-mem-"));
  const w = (f, t) => fs.writeFileSync(path.join(dir, f), t);
  const fm = (name, desc, meta = "") => `---\nname: ${name}\ndescription: ${desc}\nmetadata:\n  type: feedback\n${meta}---\n\nbody\n`;
  w("feedback_a.md", fm("a", "rule A"));
  w("feedback_b.md", fm("b", "rule B"));
  w("project_orphan.md", fm("orphan", "never indexed by hand"));
  w("MEMORY.md", [
    "- [Rule A](feedback_a.md) — **Jake 2026-11-07:** keep `x: y` \"quoted\" exactly",
    "- [Rule B](feedback_b.md) — b hook",
    "- [B again](feedback_b.md) — second line for b",
    "- [Gone](feedback_missing.md) — dead link",
  ].join("\n") + "\n");
  let state = [{ name: "open PRs", line: "Open PRs (1): #401 3b7447c4 draft" }];
  const sources = () => state;
  const results = [];
  const check = (name, cond) => results.push([name, !!cond]);

  migrate(dir);
  let out = build({ memDir: dir, sources });
  check("migration keeps a hand line byte-for-byte (backticks, colons, quotes, **)",
    out.hot.includes("- [Rule A](feedback_a.md) — **Jake 2026-11-07:** keep `x: y` \"quoted\" exactly"));
  check("a file linked twice gets one line carrying both hooks",
    (out.hot.match(/\(feedback_b\.md\)/g) || []).length === 1 && out.hot.includes("— b hook") && out.hot.includes("second line for b"));
  check("a dead link cannot appear", !out.hot.includes("feedback_missing") && !out.archive.includes("feedback_missing"));
  check("an orphan file is listed (archive), not lost", out.archive.includes("(project_orphan.md)") && !out.hot.includes("(project_orphan.md)"));
  check("hand order is kept for pinned lines", out.hot.indexOf("feedback_a.md") < out.hot.indexOf("feedback_b.md"));
  check("state line rendered", out.hot.includes("- Open PRs (1): #401 3b7447c4 draft"));
  check("pin parsed from a string", collectMemories(dir).filter(m => m.pin).length === 2);

  // --check semantics through the same comparison the CLI uses.
  fs.writeFileSync(path.join(dir, "MEMORY.md"), out.hot);
  fs.writeFileSync(path.join(dir, "MEMORY-ARCHIVE.md"), out.archive);
  check("fresh index → check 0", checkCode(dir, sources) === 0);
  fs.appendFileSync(path.join(dir, "MEMORY.md"), "- [Hand](feedback_a.md) — a hand edit\n");
  check("hand edit → check 1", checkCode(dir, sources) === 1);
  fs.writeFileSync(path.join(dir, "MEMORY.md"), out.hot);
  state = [{ name: "open PRs", line: "Open PRs (1): #401 deadbeef draft" }];
  check("a moved PR head → check 1 (stale vs source)", checkCode(dir, sources) === 1);
  state = [{ name: "open PRs", unavailable: "gh: not logged in" }];
  check("an unreadable source → check 2, never green", checkCode(dir, sources) === 2);
  const tok = "ghp_" + "q".repeat(30);
  state = [{ name: "open PRs", unavailable: `gh: bad header Authorization: token ${tok}` }];
  const leaked = build({ memDir: dir, sources }).hot;
  check("an UNAVAILABLE reason carrying a token is redacted in MEMORY.md", !leaked.includes(tok) && /redacted GitHub token/.test(leaked));
  state = [{ name: "open PRs", line: "Open PRs (1): #401 3b7447c4 draft" }];

  w("feedback_a.md", setMetadata(fs.readFileSync(path.join(dir, "feedback_a.md"), "utf8"), { hook: "token ghp_" + "y".repeat(30) }));
  let threw = ""; try { build({ memDir: dir, sources }); } catch (e) { threw = e.message; }
  check("a credential value in a hook fails the build, naming the file", /feedback_a\.md/.test(threw) && !/ghp_/.test(threw));
  w("feedback_a.md", fm("a", "rule A", "  pin: true\n"));
  for (let i = 0; i < 70; i++) w(`feedback_big${i}.md`, fm(`big${i}`, "z ".repeat(190), "  pin: true\n"));
  threw = ""; try { build({ memDir: dir, sources }); } catch (e) { threw = e.message; }
  check("over the load cap fails the build", /load cap/.test(threw));

  fs.rmSync(dir, { recursive: true, force: true });
  const bad = results.filter(([, ok]) => !ok);
  for (const [n] of bad) console.log(`  ✗ memory index: ${n}`);
  console.log(bad.length ? `✗ memory index: ${bad.length} of ${results.length} self-test checks failed`
    : `  ✓ memory index: ${results.length} self-test checks (migration verbatim, one line per file, check 0/1/2, secrets, load cap)`);
  return bad.length ? 1 : 0;
}

function checkCode(memDir, sources) {
  const out = build({ memDir, sources });
  const same = f => { try { return fs.readFileSync(path.join(memDir, f), "utf8") === out[f === "MEMORY.md" ? "hot" : "archive"]; } catch { return false; } };
  if (out.unavailable.length) return 2;
  return same("MEMORY.md") && same("MEMORY-ARCHIVE.md") ? 0 : 1;
}

// ── CLI ──────────────────────────────────────────────────────────────────
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.includes("--self-test")) process.exit(selfTest());
  const memDir = defaultMemDir();
  if (!fs.existsSync(memDir)) { console.error(`✗ memory dir not found: ${memDir}`); process.exit(2); }
  const inboxKey = `p:${mainCheckout()}`;
  const sources = liveSources({
    handoffDir: process.env.PLURSKY_HANDOFF_DIR || path.join(os.homedir(), "Plursky-private/instinct"),
    inboxKey,
    inboxStore: () => {
      if (process.env.PLURSKY_INBOX_STORE) return process.env.PLURSKY_INBOX_STORE;
      const d = path.join(os.homedir(), ".claude/plugins/store");
      const f = fs.existsSync(d) && fs.readdirSync(d).find(x => /^inbox_inbox-.*\.json$/.test(x));
      return f ? path.join(d, f) : null;
    },
  });
  if (args.includes("--migrate-from-index")) {
    const n = migrate(memDir);
    console.log(`  migrated ${n.size} indexed memories into their own frontmatter (pin, pin_order, title, hook)`);
  }
  try {
    if (args.includes("--check")) {
      const code = checkCode(memDir, sources);
      const msg = { 0: "✓ memory index is fresh against its sources",
        1: "✗ memory index is STALE (a source moved or someone hand-edited it): run node scripts/memory/build-memory-index.mjs",
        2: "✗ memory index CANNOT BE VERIFIED: a source was unreadable (see the ⚠ line after a rebuild)" }[code];
      console.log(`  ${msg} (${memDir})`);
      process.exit(code);
    }
    const out = build({ memDir, sources });
    fs.writeFileSync(path.join(memDir, "MEMORY.md"), out.hot);
    fs.writeFileSync(path.join(memDir, "MEMORY-ARCHIVE.md"), out.archive);
    console.log(`  ✓ MEMORY.md ${out.bytes} B (cap ${LOAD_CAP}), ${out.pinned} pinned · MEMORY-ARCHIVE.md ${out.cold} un-pinned · ${memDir}`);
    for (const u of out.unavailable) console.log(`  ⚠ ${u.name} UNAVAILABLE: ${u.unavailable}`);
    process.exit(out.unavailable.length ? 2 : 0);
  } catch (e) { console.error(`  ✗ ${e.message}`); process.exit(1); }
}
