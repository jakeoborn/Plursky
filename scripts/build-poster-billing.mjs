#!/usr/bin/env node
// Item 4 (Oct 16 spec): an act's tier is its OFFICIAL POSTER BILLING, not a
// set-time guess. Until now III Points hardcoded every act to tier 2.
//
// Source: the festival's own lineup-by-day graphic, already transcribed and
// reconciled act by act (docs/qa/reports/<fid>-day-split/reconciliation.tsv,
// with the graphic's URL and sha256 in graphic.tsv). The graphic bills by ZONE,
// and a zone's type size is its rank:
//   centre oval + 444 extended-sets box  → 3  "Top billed" (largest type)
//   the four rings                       → 2  (one smaller size, all four)
//   the local panel                      → 1  (smallest type)
// The graphic has no single headline row (every centre name is one size), so
// it ranks nobody above "Top billed". An act not on the graphic gets no poster
// tier: it keeps the module default and no badge.
//
// Writes the BILLING block of data/festivals/<fid>.js (act id → tier) and
// docs/qa/reports/<fid>-billing/billing.tsv (the row-by-row report).
//   node scripts/build-poster-billing.mjs           # write
//   node scripts/build-poster-billing.mjs --check   # fail if either is stale
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
export const ZONE_TIER = { centre: 3, "444": 3, "ring-red": 2, "ring-pink": 2, "ring-lilac": 2, "ring-blue": 2, local: 1 };
const FESTIVALS = ["iii-points-2026"];

const tsv = p => readFileSync(join(ROOT, p), "utf8").split("\n");
let stale = 0;
for (const fid of FESTIVALS) {
  const dir = `docs/qa/reports/${fid}-day-split`;
  const graphicHead = tsv(`${dir}/graphic.tsv`).filter(l => l.startsWith("#"));
  const src = (graphicHead.join("\n").match(/Source: (\S+)/) || [])[1];
  const sha = (graphicHead.join("\n").match(/sha256 ([0-9a-f]{64})/) || [])[1];
  const read = (graphicHead[0].match(/(\d{4}-\d{2}-\d{2})/) || [])[1];
  if (!src || !sha || !read) throw new Error(`${dir}/graphic.tsv: source URL, sha256 or transcription date missing from its header`);

  const lines = tsv(`${dir}/reconciliation.tsv`);
  const head = lines.findIndex(l => l.startsWith("act_id\t"));
  const cols = lines[head].split("\t");
  const rows = [];
  for (const l of lines.slice(head + 1)) {
    if (!l.trim() || l.startsWith("#")) break;            // the section after the act rows is graphic-only billings
    const r = Object.fromEntries(l.split("\t").map((v, i) => [cols[i], v]));
    const zone = r.graphic_zone || "";
    if (zone && !(zone in ZONE_TIER)) throw new Error(`${fid}: unknown graphic zone "${zone}" on ${r.act_id}`);
    rows.push({ id: r.act_id, name: r.shipped_name, zone, tier: zone ? ZONE_TIER[zone] : null, billing: r.graphic_billing || "", evidence: r.evidence });
  }
  // Join on TODAY's lineup, not the list the reconciliation was read from: the
  // official set-times grid later swapped acts (fakemink and Nick León B2B
  // Safety Trance out; Nettspend, solo Nick León, Homicide Jenny, nxtel in).
  const win = {}; win.window = win;
  vm.runInNewContext(readFileSync(join(ROOT, "data", "festivals", `${fid}.js`), "utf8"), win);
  const live = (win.PLURSKY_FESTIVALS?.[fid]?.artists || []);
  if (live.length < 100) throw new Error(`${fid}.js: only ${live.length} acts loaded (the module loader broke?)`);
  const liveIds = new Set(live.map(a => a.id));
  const gone = rows.filter(r => !liveIds.has(r.id));
  rows.splice(0, rows.length, ...rows.filter(r => liveIds.has(r.id)));
  const known = new Set(rows.map(r => r.id));
  for (const a of live) if (!known.has(a.id)) rows.push({ id: a.id, name: a.name, zone: "", tier: null, billing: "", evidence: "not_on_graphic (in the lineup after the graphic was reconciled)" });
  const tiered = rows.filter(r => r.tier != null);

  // The module's BILLING block.
  const modPath = join(ROOT, "data", "festivals", `${fid}.js`);
  const mod = readFileSync(modPath, "utf8");
  const block = [
    "  // BILLING:BEGIN — generated by scripts/build-poster-billing.mjs; do not edit.",
    "  // 3 = centre oval / 444 box (top billed), 2 = the rings, 1 = the local panel.",
    `  const BILLING_SOURCE = { url: ${JSON.stringify(src)}, sha256: ${JSON.stringify(sha)}, transcribed: ${JSON.stringify(read)} };`,
    "  const BILLING_TIER = {",
    ...tiered.map(r => `    ${JSON.stringify(r.id)}: ${r.tier},`),
    "  };",
    "  // BILLING:END",
  ].join("\n");
  const re = /  \/\/ BILLING:BEGIN[\s\S]*?\/\/ BILLING:END/;
  if (!re.test(mod)) throw new Error(`${fid}.js: no BILLING:BEGIN/END block`);
  const nextMod = mod.replace(re, block);

  // The report: every act row, its billing as printed, its zone and tier.
  const report = [
    `# ${fid}: poster billing tier, act by act. Generated by scripts/build-poster-billing.mjs from ${dir}/reconciliation.tsv.`,
    `# Source: ${src}`,
    `# sha256 ${sha} · transcribed ${read}. Zone → tier: ${Object.entries(ZONE_TIER).map(([z, t]) => `${z}=${t}`).join(", ")}; not on the graphic = no poster tier.`,
    `# ${rows.length} acts: ${[3, 2, 1].map(t => `tier ${t} ${rows.filter(r => r.tier === t).length}`).join(", ")}, not on the graphic ${rows.filter(r => r.tier == null).length}.`,
    "act_id\tshipped_name\tgraphic_billing\tgraphic_zone\tposter_tier\tevidence",
    ...rows.map(r => [r.id, r.name, r.billing, r.zone, r.tier ?? "", r.evidence].join("\t")),
    // The graphic's billings with no act in the lineup (removed, or never listed): no tier.
    ...(() => {
      const i = lines.findIndex((l, n) => n > head && l.startsWith("#"));
      const extra = (i < 0 ? [] : lines.slice(i + 1)).filter(l => l.trim() && !l.startsWith("#")).map(l => l.split("\t"))
        .map(c => ["", "", c[cols.indexOf("graphic_billing")], c[cols.indexOf("graphic_zone")], "", `${c[cols.indexOf("evidence")]}: ${c[cols.indexOf("note")] || ""}`].join("\t"));
      const dropped = gone.map(r => [r.id, r.name, r.billing, r.zone, "", `${r.evidence}; not in today's lineup`].join("\t"));
      return extra.length || dropped.length ? ["# On the graphic, no act in the lineup (no tier):", ...dropped, ...extra] : [];
    })(),
  ].join("\n") + "\n";
  const repDir = join(ROOT, "docs", "qa", "reports", `${fid}-billing`);
  const repPath = join(repDir, "billing.tsv");
  let oldRep = ""; try { oldRep = readFileSync(repPath, "utf8"); } catch {}

  if (CHECK) {
    if (nextMod !== mod) { stale++; console.error(`✗ ${fid}.js BILLING block is stale — run node scripts/build-poster-billing.mjs`); }
    if (oldRep !== report) { stale++; console.error(`✗ ${repPath} is stale — run node scripts/build-poster-billing.mjs`); }
  } else {
    writeFileSync(modPath, nextMod);
    mkdirSync(repDir, { recursive: true }); writeFileSync(repPath, report);
  }
  console.log(`${CHECK ? "checked" : "wrote"} ${fid}: ${rows.length} acts, ${tiered.length} poster-tiered (${[3, 2, 1].map(t => `${t}:${rows.filter(r => r.tier === t).length}`).join(" ")})`);
}
if (stale) process.exit(1);
